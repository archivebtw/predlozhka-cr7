create table if not exists public.game_suggestions (
  id bigint generated by default as identity primary key,
  steam_app_id bigint not null unique check (steam_app_id > 0),
  steam_url text not null check (char_length(steam_url) between 20 and 500),
  title text not null check (char_length(title) between 1 and 120),
  cover_url text not null default '' check (char_length(cover_url) <= 1000),
  description text not null default '' check (char_length(description) <= 2000),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected', 'selected', 'completed', 'archived')),
  rejection_reason text not null default '' check (char_length(rejection_reason) <= 500),
  submitted_by uuid default auth.uid() references auth.users(id) on delete set null,
  moderated_by uuid references auth.users(id) on delete set null,
  moderated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.suggestion_supports (
  suggestion_id bigint not null references public.game_suggestions(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (suggestion_id, user_id)
);

create table if not exists public.suggestion_votes (
  suggestion_id bigint not null references public.game_suggestions(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (suggestion_id, user_id)
);

create table if not exists public.suggestion_comments (
  id bigint generated by default as identity primary key,
  suggestion_id bigint not null references public.game_suggestions(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  body text not null check (char_length(btrim(body)) between 1 and 300),
  is_hidden boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (suggestion_id, user_id)
);

create index if not exists game_suggestions_status_created_idx
  on public.game_suggestions (status, created_at desc);
create index if not exists suggestion_supports_suggestion_idx
  on public.suggestion_supports (suggestion_id);
create index if not exists suggestion_votes_suggestion_idx
  on public.suggestion_votes (suggestion_id);
create index if not exists suggestion_comments_suggestion_created_idx
  on public.suggestion_comments (suggestion_id, created_at);

